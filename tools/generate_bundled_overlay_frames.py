#!/usr/bin/env python3
"""Generate deterministic RGB565 animation samples from bundled overlay sources."""
from pathlib import Path
import json
from PIL import Image, ImageSequence, ImageOps

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets' / 'overlay-library'
MANIFEST = ASSETS / 'embedded-assets-manifest.json'
OUT = ROOT / 'src' / 'BundledOverlayFrames.h'
W, H, N = 160, 90, 10

def rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)

def read_frames(path):
    im = Image.open(path)
    frames = []
    for fr in ImageSequence.Iterator(im):
        fr = fr.convert('RGB')
        fr = ImageOps.fit(fr, (W, H), method=Image.Resampling.LANCZOS, centering=(0.5, 0.5))
        frames.append(fr.copy())
    return frames or [ImageOps.fit(im.convert('RGB'), (W, H))]

manifest = json.loads(MANIFEST.read_text(encoding='utf-8'))
assets = manifest['assets']
assert len(assets) == 21
lines = [
    '// Generated by tools/generate_bundled_overlay_frames.py. RGB565; 160x90; ten temporal samples per asset.',
    '#pragma once', '#include <cstdint>',
    'static constexpr int kBundledOverlayCount = 21;',
    f'static constexpr int kBundledOverlayFrames = {N};',
    f'static constexpr int kBundledOverlayWidth = {W};',
    f'static constexpr int kBundledOverlayHeight = {H};',
    f'static const uint16_t kBundledOverlayRGB565[21][{N}][{H}][{W}] = {{'
]
for asset in assets:
    frames = read_frames(ASSETS / asset['group'] / asset['filename'])
    lines.append('  { // ' + asset['group'] + '/' + asset['filename'].replace('*/','') )
    for sample in range(N):
        idx = round(sample * (len(frames)-1) / max(1, N-1))
        pix = list(frames[idx].getdata())
        lines.append('    {')
        for y in range(H):
            row = ','.join(str(rgb565(*pix[y*W+x])) for x in range(W))
            lines.append('      {' + row + '}' + (',' if y < H-1 else ''))
        lines.append('    }' + (',' if sample < N-1 else ''))
    lines.append('  },')
lines.append('};')
OUT.write_text('\n'.join(lines)+'\n', encoding='utf-8')
manifest['frame_samples_per_asset'] = N
manifest['embedded_preview_size'] = [W, H]
manifest['pixel_format'] = 'RGB565'
manifest['generator'] = 'tools/generate_bundled_overlay_frames.py'
MANIFEST.write_text(json.dumps(manifest, indent=2, ensure_ascii=False)+'\n', encoding='utf-8')
print(f'Generated {OUT.relative_to(ROOT)}: {len(assets)} assets x {N} frames x {W}x{H}')
